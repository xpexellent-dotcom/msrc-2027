import { afterEach, describe, expect, it, vi } from "vitest";
import { SYNTHETIC_CORPUS, SYNTHETIC_TIMESTAMP } from "../../evaluation/ai-assessment/corpus.ts";
import { createMockedProvider, evaluationOutcome, manualOutcome, prepareSyntheticCases, runMockedEvaluation } from "../../evaluation/ai-assessment/harness.ts";
