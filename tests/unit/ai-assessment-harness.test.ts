const now = () => SYNTHETIC_TIMESTAMP;
const keyCanary = "local-key-synthetic-never-log";
const environment = { AI_SYNTHETIC_API_KEY: keyCanary, AI_SYNTHETIC_SPEND_LIMIT_CONFIGURED: "yes" };
const submitArgs = ["submit", "--live-synthetic", "--budget-usd", "10", "--input-price-ceiling", "8", "--output-price-ceiling", "40", "--max-tokens", "1024", "--thinking", "disabled"];
const temporaryDirectories: string[] = [];
async function temporaryDirectory() {
  const directory = await mkdtemp(join(tmpdir(), "ai-synthetic-test-"));
  temporaryDirectories.push(directory); return directory;
}
afterEach(async () => {
  vi.unstubAllGlobals();
  vi.unstubAllEnvs();
  for (const directory of temporaryDirectories.splice(0)) {
    // Delete only temporary directories generated by this suite.
    if (resolve(directory).startsWith(resolve(tmpdir()) + sep) && basename(directory).startsWith("ai-synthetic-test-")) await rm(directory, { recursive: true, force: true });
  }
});

async function validOutcomes(): Promise<EvaluationOutcome[]> {
  const provider = createMockedProvider();
  return Promise.all(prepareSyntheticCases({ maxTokens: 1024, thinking: "disabled" }).map(async (item) => {
    if (!item.request) return manualOutcome(item.example, item.inputFailure!, now(), "mock_deepseek");
    try { return evaluationOutcome(item.example, await provider.assess(item.request, item.example), now(), "mock_deepseek"); }
    catch { return manualOutcome(item.example, "provider_unavailable", now(), "mock_deepseek"); }
  }));
}

describe("AI-01/02/04/06 synthetic corpus and mocked provider", () => {
  it("contains 29 frozen, exclusively synthetic cases with required study/failure diversity", () => {
    expect(SYNTHETIC_CORPUS).toHaveLength(29);
    expect(new Set(SYNTHETIC_CORPUS.map((entry) => entry.id)).size).toBe(29);
    expect(Object.isFrozen(SYNTHETIC_CORPUS)).toBe(true);
    for (const example of SYNTHETIC_CORPUS) {
      expect(example.synthetic).toBe(true); expect(Object.isFrozen(example.snapshot)).toBe(true);
    }
    for (const tag of ["strong", "weak", "ongoing", "randomized", "case_report", "systematic_review", "diagnostic_accuracy", "unsupported_claim", "injection", "malformed_input", "identity_leak"]) {
      expect(SYNTHETIC_CORPUS.some((entry) => entry.tags.includes(tag)), tag).toBe(true);
    }
    expect(SYNTHETIC_RUBRIC.status).toBe("UNAPPROVED");
  });

  it.each(SYNTHETIC_CORPUS.map((example) => [example.id, example.expectedInput] as const))("screens %s locally against its declared expectation", (id, expected) => {
    const prepared = prepareSyntheticCases({ thinking: "disabled", maxTokens: 1024 }).find((item) => item.example.id === id)!;
    expect(prepared.inputFailure ?? "allowed").toBe(expected);
    expect(Boolean(prepared.request)).toBe(expected === "allowed");
  });

  it("runs all cases against a mocked provider and never dispatches the eleven denied inputs", async () => {
    const provider = createMockedProvider();
    const assess = vi.fn(provider.assess);
    const report = await runMockedEvaluation({ assess }, { now });
    expect(assess).toHaveBeenCalledTimes(18);
    expect(report.summary).toMatchObject({ total: 29, completed: 12, manualReview: 17, unassessedByHuman: 29 });
    for (const row of report.rows) {
      expect(row.manualReviewAvailable).toBe(true);
      expect(row.humanAssessmentSource).toBe("UNASSESSED");
      expect(row.comparison.every((item) => item.humanIndependentScore === null && item.humanFinalScore === null && item.modelMinusHuman === null)).toBe(true);
    }
    expect(report.activationApproval).toBe("NOT_GRANTED"); expect(report.acceptanceThreshold).toBeNull();
  });

  it("allows generic EN/AR tertiary-hospital settings with a typed warning but blocks named submitter institution matches", async () => {
    const prepared = prepareSyntheticCases({ thinking: "disabled", maxTokens: 1024 });
    for (const number of [26, 27]) {
      const generic = prepared[number - 1];
      expect(generic.inputFailure).toBeNull(); expect(generic.request).not.toBeNull();
      expect(generic.sanitizationWarnings).toEqual(["generic_institution_mention"]);
    }
    for (const number of [28, 29]) {
      expect(prepared[number - 1].inputFailure).toBe("identity_leak");
      expect(prepared[number - 1].request).toBeNull();
    }
    const report = await runMockedEvaluation(undefined, { now });
    for (const number of [26, 27]) expect(report.rows[number - 1].provenance.sanitizationWarnings).toEqual(["generic_institution_mention"]);
    const failed = await runMockedEvaluation({ assess: async () => { throw new Error("synthetic outage"); } }, { now });
    expect(failed.rows[25].status).toBe("manual_review");
    expect(failed.rows[25].provenance.sanitizationWarnings).toEqual(["generic_institution_mention"]);
    expect(JSON.stringify(report.rows[25].provenance)).not.toContain("tertiary hospital");
    expect(JSON.stringify(report.rows[26].provenance)).not.toContain("مستشفى");
  });
  it.each([[26, "a tertiary hospital in Jeddah"], [27, "مستشفى مرجعي في جدة"]] as const)("still blocks generic wording in case %s when it exactly matches local institution identity", (number, ownInstitution) => {
    const snapshot = SYNTHETIC_CORPUS[number - 1].snapshot;
    const sanitized = sanitizeSnapshot({ ...snapshot, identity: { authorNames: [], institutions: [ownInstitution] } });
    expect(sanitized).toMatchObject({ ok: false, reason: "identity_leak", flags: ["institution"] });
  });

  it("sends only five allowlisted fields, with fixed rubric/rules in system and untrusted injections in user", () => {
    const requests = prepareSyntheticCases({ thinking: "disabled", maxTokens: 1024 }).filter((item) => item.request);
    const baselineSystem = requests[0].request!.messages[0];
    for (const prepared of requests) {
      const request = prepared.request!;
      expect(Object.keys(JSON.parse(request.messages[1].content)).sort()).toEqual(["body", "completionStatus", "specialty", "studyType", "title"]);
      expect(request.messages[0]).toEqual(baselineSystem);
      expect(request.messages.map((item) => item.role)).toEqual(["system", "user"]);
      expect(request).not.toHaveProperty("tools");
      expect(request.thinking).toEqual({ type: "disabled" });
      expect(request.response_format).toEqual({ type: "json_object" });
      for (const key of ["system", "output_config", "fallbacks", "betas", "cache_control"]) expect(request).not.toHaveProperty(key);
      expect(request.model).toBe(SYNTHETIC_MODEL);
      expect(JSON.stringify(request)).not.toContain(prepared.example.snapshot.id);
      if (prepared.example.tags.includes("injection")) {
        const body = (prepared.example.snapshot.scientific as { body: string }).body;
        expect(request.messages[1].content).toContain(JSON.stringify(body).slice(1, -1));
        expect(request.messages[0].content).not.toContain(body);
      }
    }
  });

  it("keeps refusal and truncation content unread while returning the manual path", () => {
    for (const finish_reason of ["content_filter", "length", "tool_calls", "insufficient_system_resource"]) {
      const message = { model: SYNTHETIC_MODEL, choices: [{ finish_reason, get message() { throw new Error("CONTENT_MUST_NOT_BE_READ"); } }] };
      const output = evaluationOutcome(SYNTHETIC_CORPUS[0], message, now(), "mock_deepseek");
      expect(output.status).toBe("manual_review"); expect(output.output).toBeNull();
    }
  });

  it.each([
    ["length", "incomplete_output"], ["content_filter", "refusal"],
    ["tool_calls", "incomplete_output"], ["insufficient_system_resource", "incomplete_output"],
    ["unknown", "incomplete_output"], [null, "incomplete_output"],
  ])("maps finish reason %s to %s", (finish_reason, reason) => {
    const result = evaluationOutcome(SYNTHETIC_CORPUS[0], { model: SYNTHETIC_MODEL,
      choices: [{ finish_reason, message: { role: "assistant", content: "{}" } }] }, now(), "mock_deepseek");
    expect(result).toMatchObject({ status: "manual_review", reason, output: null });
  });

  it.each([0, 2])("rejects %s choices without reading their messages", (count) => {
    const message = { model: SYNTHETIC_MODEL, choices: Array.from({ length: count }, () => ({ finish_reason: "stop",
      get message() { throw new Error("MULTIPLE_CHOICE_CONTENT_MUST_NOT_BE_READ"); } })) };
    expect(evaluationOutcome(SYNTHETIC_CORPUS[0], message, now(), "mock_deepseek")).toMatchObject({ status: "manual_review", reason: "invalid_output", output: null });
  });

  it("discards reasoning without reading, retaining or reporting it", async () => {
    const provider = createMockedProvider();
    const report = await runMockedEvaluation({ assess: async (request, example) => {
      const message = await provider.assess(request, example) as { choices: { message: object }[] };
      Object.defineProperty(message.choices[0].message, "reasoning_content", { enumerable: true,
        get() { throw new Error("REASONING_MUST_NOT_BE_READ_OR_COPIED"); } });
      return message;
    } }, { now });
    expect(report.summary).toMatchObject({ total: 29, completed: 12, manualReview: 17 });
    expect(JSON.stringify(report)).not.toContain("reasoning_content");
    expect(JSON.stringify(report)).not.toContain("REASONING_MUST_NOT_BE_READ_OR_COPIED");
  });

  it("records returned-model provenance and refuses a valid score from an unexpected model", async () => {
    const prepared = prepareSyntheticCases({ thinking: "disabled", maxTokens: 1024 })[0];
    const message = await createMockedProvider().assess(prepared.request!, prepared.example) as Record<string, unknown>;
    const valid = evaluationOutcome(prepared.example, message, now(), "mock_deepseek");
    expect(valid.provenance).toMatchObject({ requestedModel: SYNTHETIC_MODEL, model: SYNTHETIC_MODEL });
    const unexpected = evaluationOutcome(prepared.example, { ...message, model: "deepseek-unapproved-test-model" }, now(), "mock_deepseek");
    expect(unexpected.status).toBe("manual_review"); expect(unexpected.reason).toBe("unexpected_model");
    expect(unexpected.provenance.model).toBe("deepseek-unapproved-test-model");
    expect(manualOutcome(prepared.example, "identity_leak", now(), "mock_deepseek").provenance.model).toBeNull();
  });

  it("does not retain raw provider errors, credentials or manuscript bodies", async () => {
    const report = await runMockedEvaluation({ assess: async () => { throw new Error(`${keyCanary}: raw manuscript`); } }, { now });
    expect(JSON.stringify(report)).not.toContain(keyCanary); expect(JSON.stringify(report)).not.toContain("raw manuscript");
    expect(report.summary.completed).toBe(0);
    expect(report.rows.every((row) => row.manualReviewAvailable)).toBe(true);
  });
});

describe("AI-03/04/06 comparison report with genuine human values kept separate", () => {
  const fixture: HumanAssessment = {
    caseId: SYNTHETIC_CORPUS[0].id, snapshotVersion: "1", rubricVersion: SYNTHETIC_RUBRIC.version,
    source: "synthetic_test_fixture", evidenceReference: "invented-comparison-fixture",
    criteria: SYNTHETIC_RUBRIC.criteria.map((item, index) => ({ criterionId: item.id, independentScore: [4, 2, 3][index], finalScore: 3, overrideReason: index === 2 ? null : "Invented override reason for report-format test." })),
  };
  it("compares model/human scores, overrides and disagreement without pooling fixture/scientific sources", async () => {
    const scientific: HumanAssessment = { ...fixture, caseId: SYNTHETIC_CORPUS[1].id, source: "scientific_lead", evidenceReference: "synthetic-test-scientific-record", criteria: fixture.criteria.map((item) => ({ ...item, independentScore: 3, finalScore: 3, overrideReason: null })) };
    const report = await runMockedEvaluation(undefined, { now, humanAssessments: [fixture, scientific] });
    expect(report.rows[0].comparison.map((item) => item.modelMinusHuman)).toEqual([-1, 1, 0]);
    expect(report.summary.disagreementBySource).toEqual([
      { source: "scientific_lead", comparedCriteria: 3, differentScores: 0, meanAbsoluteDifference: 0, overrides: 0 },
      { source: "synthetic_test_fixture", comparedCriteria: 3, differentScores: 2, meanAbsoluteDifference: 2 / 3, overrides: 2 },
    ]);
    expect(report.rows[2].humanAssessmentSource).toBe("UNASSESSED");
  });
  it.each([
    { rubricVersion: "another-rubric" }, { snapshotVersion: "2" }, { caseId: "real-abstract" },
    { criteria: [] }, { criteria: fixture.criteria.map((item) => ({ ...item, finalScore: 99 })) },
    { criteria: fixture.criteria.map((item) => ({ ...item, overrideReason: null })) },
  ])("rejects stale, real-case, missing, out-of-range or unexplained human records %j", async (patch) => {
    await expect(runMockedEvaluation(undefined, { now, humanAssessments: [{ ...fixture, ...patch }] })).rejects.toThrow("invalid_human_evaluation_record");
  });
  it("rejects mismatched provenance, invalid scores and incomplete case coverage", async () => {
    const outcomes = await validOutcomes();
    const options = { generatedAt: now(), execution: "mock" as const };
    expect(() => createEvaluationReport(outcomes.slice(1), SYNTHETIC_RUBRIC, options)).toThrow("incomplete_evaluation_report");
    expect(() => createEvaluationReport([{ ...outcomes[0], provenance: { ...outcomes[0].provenance, snapshotVersion: "2" } }, ...outcomes.slice(1)], SYNTHETIC_RUBRIC, options)).toThrow("invalid_evaluation_provenance");
    const invalid = { ...outcomes[0], output: { ...outcomes[0].output!, criteria: outcomes[0].output!.criteria.map((item) => ({ ...item, score: 99 })) } };
    expect(() => createEvaluationReport([invalid, ...outcomes.slice(1)], SYNTHETIC_RUBRIC, options)).toThrow("invalid_evaluation_outcome");
    expect(() => createEvaluationReport(outcomes, SYNTHETIC_RUBRIC, { ...options, generatedAt: "invalid" })).toThrow("invalid_evaluation_timestamp");
  });
  it.each([
    { label: "unknown category containing raw text", warnings: ["raw hospital identifier"] },
    { label: "duplicate warning", warnings: ["generic_institution_mention", "generic_institution_mention"] },
    { label: "omitted warning", warnings: [] },
    { label: "untyped warning object", warnings: [{ category: "generic_institution_mention", body: "raw manuscript" }] },
  ])("rejects unsafe or altered generic-warning provenance: $label", async ({ warnings }) => {
    const outcomes = await validOutcomes();
    const invalid = { ...outcomes[25], provenance: { ...outcomes[25].provenance, sanitizationWarnings: warnings } } as unknown as EvaluationOutcome;
    expect(() => createEvaluationReport([...outcomes.slice(0, 25), invalid, ...outcomes.slice(26)], SYNTHETIC_RUBRIC, { generatedAt: now(), execution: "mock" })).toThrow("invalid_evaluation_provenance");
  });
  it("rejects fabricated warnings and extra raw provenance fields", async () => {
    const outcomes = await validOutcomes();
    const fabricated = { ...outcomes[0], provenance: { ...outcomes[0].provenance, sanitizationWarnings: ["generic_institution_mention"] as const } };
    expect(() => createEvaluationReport([fabricated, ...outcomes.slice(1)], SYNTHETIC_RUBRIC, { generatedAt: now(), execution: "mock" })).toThrow("invalid_evaluation_provenance");
    const extra = { ...outcomes[0], provenance: { ...outcomes[0].provenance, manuscript: "secret body" } };
    expect(() => createEvaluationReport([extra, ...outcomes.slice(1)], SYNTHETIC_RUBRIC, { generatedAt: now(), execution: "mock" })).toThrow("invalid_evaluation_provenance");
  });
  it.each(["anthropic", "mock_anthropic", "deepseek"])("rejects %s provenance in a mock DeepSeek report", async (provider) => {
    const outcomes = await validOutcomes();
    const invalid = { ...outcomes[0], provenance: { ...outcomes[0].provenance, provider } };
    expect(() => createEvaluationReport([invalid, ...outcomes.slice(1)], SYNTHETIC_RUBRIC, { generatedAt: now(), execution: "mock" })).toThrow("invalid_evaluation_provenance");
  });
  it("supports only manual outcomes in an explicitly unsupported DeepSeek batch report", async () => {
    const outcomes = SYNTHETIC_CORPUS.map((example) => manualOutcome(example, example.expectedInput === "allowed" ? "batch_unsupported" : example.expectedInput, now(), "deepseek"));
    const report = createEvaluationReport(outcomes, SYNTHETIC_RUBRIC, { generatedAt: now(), execution: "unsupported_synthetic_batch" });
    expect(report.summary).toMatchObject({ total: 29, completed: 0, manualReview: 29 });
    expect(report.rows.every((row) => row.provenance.model === null)).toBe(true);
    const valid = (await validOutcomes())[0];
    const completed = { ...valid, provenance: { ...valid.provenance, provider: "deepseek" } };
    expect(() => createEvaluationReport([completed, ...outcomes.slice(1)], SYNTHETIC_RUBRIC, { generatedAt: now(), execution: "unsupported_synthetic_batch" })).toThrow("invalid_evaluation_outcome");
  });
});


